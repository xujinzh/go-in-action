/*
Go 语言中程序的初始化和执行遵循严格的自底向上、由深到浅的逻辑。

其核心的执行顺序为：
导入的包 (Import) -> 常量 (Const) -> 全局变量 (Var) -> 初始化函数 (Init) -> 主函数 (Main)

	[开始]
	  │
	  ▼

[1. 递归导入并初始化所有依赖包 (Import)] ──────► 从最深层的叶子包开始初始化

	│
	▼

[2. 初始化当前包的常量 (Const)]

	│
	▼

[3. 初始化当前包的全局变量 (Var)] ───────────► 如果变量赋值调用了函数，先执行该函数

	│
	▼

[4. 执行当前包的 init() 函数] ───────────────► 同一包内多个 init 依序执行

	│
	▼

[5. 执行 main() 函数] ─────────────────────► 仅在 main 包中触发，程序正式运行

	  │
	  ▼
	[结束]

二、 详细规则与特殊场景

1. 多个包的依赖顺序（深度优先）如果 main 包导入了 A 包，A 包又导入了 B 包（main -> A -> B），
Go 编译器会通过深度优先的方式进行递归初始化：
- 顺序：B 的变量/init -> A 的变量/init -> main 的变量/init。
- 唯一性：即使一个包被多次隐式或显式导入，它也只会初始化一次。

2. 包内部的初始化顺序在同一个包甚至同一个 .go 文件内部，元素的初始化严格按照以下顺序：
- const：常量最先被评估与赋值。
- var：全局变量初始化。如果变量是通过函数赋值的（例如 var V = check()），该赋值函数会先于 init() 执行。
- init()：变量全部就绪后，才会触发 init()。

3. 单个包内存在多个 init() 函数Go 语言允许在同一个包甚至同一个文件中定义多个 init() 函数：
- 同文件：按照代码中从上到下的字面书写顺序依次执行。
- 同包不同文件：Go 编译器会根据文件名字符串的升序（字母表顺序）依次传递给编译器，从而决定文件间 init() 的执行先后。
*/
package main

// 0. 最先执行的是import
import "fmt"

// 1. 常量先执行
const a = 3.14

// 2. 全局变量再执行
var (
	b = 2.71828
	c = varInit()
)

// 3. 全局变量初始化函数再执行
func varInit() int {
	fmt.Println("执行：全局变量 var 初始化")
	return 1
}

// 4. 第一个 init 函数
func init() {
	fmt.Println("执行：第一个 init() 函数")
}

// 5. 第二个 init 函数
func init() {
	fmt.Println("执行：第二个 init 函数")
}

// 6. 程序主入口，程序开始运行
func main() {
	fmt.Println("执行：main() 函数")
	fmt.Printf("a=%v, b=%v, c=%v", a, b, c)
}
